#!/usr/bin/env python3
"""SYNTHETIC multi-subject dataset generator for the attention-state model.

Default (`--generator live`): the realistic generator in synthlib.render_session. It simulates
camera-rate face samples, Core Motion and 1 Hz rPPG readings for each subject (own baselines,
calibration offsets, lighting changes, face-tracking dropouts, HR gaps and quality swings,
head-motion bursts, glances, note reading, talking, brief and sustained phone pickups, gradual lapse
onsets/offsets, ambiguous mixtures) and runs them through a Python port of the app's
AttentionFeatureExtractor (ml/synth/live_extractor.py), so the trailing-60 s counters behave exactly
like the live ones. Sessions last 10-30 min (random) unless `--seconds` is given, and are mostly
focused. About 5% of frame labels are deliberately wrong (label noise); the generator's ground truth
is kept in a trailing `true_label` column for evaluation.

`--generator legacy` reproduces the previous, simpler generator (synthlib.synth_session).

One CSV per session in the app's label-export format (t,label,lapse + the 42 FeatureFrame columns
[+ true_label]) with a "# SYNTHETIC" header comment. Not real data: never report numbers derived from
it as results without the SYNTHETIC label.

Usage: ml/.venv/bin/python ml/synth/generate_dataset.py [--subjects 24] [--sessions 2]
       [--seconds N | --min-seconds 600 --max-seconds 1800] [--seed 0] [--out ml/synth/out]
       [--generator live|legacy] [--label-noise 0.05]
"""
import argparse
import pathlib
import sys

import numpy as np

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from synthlib import (ROOT, LiveSubject, SubjectParams, synth_session, synth_session_live,  # noqa: E402
                      write_csv, write_csv_live)


def main(subjects=24, sessions=2, seconds=None, seed=0, out=None, generator="live",
         min_seconds=600, max_seconds=1800, label_noise=0.05):
    out = pathlib.Path(out or ROOT / "ml/synth/out")
    out.mkdir(parents=True, exist_ok=True)
    paths, noise, focused, total = [], 0.0, 0.0, 0.0
    for s in range(subjects):
        if generator == "legacy":
            subj = SubjectParams.sample(s, np.random.default_rng([seed, s]))
        else:
            subj = LiveSubject.sample(s, np.random.default_rng([seed, s]))
        for k in range(sessions):
            rng = np.random.default_rng([seed, s, k, 1])
            p = out / f"SYNTHETIC_subj{s:02d}_sess{k}.csv"
            if generator == "legacy":
                secs = seconds or 600
                t, st, F = synth_session(secs, rng, subj)
                write_csv(p, t, st, F,
                          f"SYNTHETIC multi-subject session generated by ml/synth/generate_dataset.py "
                          f"(legacy generator, seed={seed}). Not real data.\nsubject={s} session={k}\n"
                          f"params={subj.to_json()}")
            else:
                secs = float(seconds) if seconds else float(rng.uniform(min_seconds, max_seconds))
                t, lab, true, F, info = synth_session_live(secs, rng, subj, label_noise=label_noise)
                write_csv_live(p, t, lab, true, F,
                               f"SYNTHETIC multi-subject session generated by ml/synth/generate_dataset.py "
                               f"(live generator: simulated sensors -> port of AttentionFeatureExtractor, "
                               f"seed={seed}). Not real data.\nsubject={s} session={k} seconds={secs:.0f} "
                               f"label_noise={info['label_noise_frac']:.3f}\nparams={subj.to_json()}")
                noise += info["label_noise_frac"] * secs; focused += info["focused_frac"] * secs
            total += secs
            paths.append(p)
    msg = f"wrote {len(paths)} SYNTHETIC sessions ({subjects} subjects x {sessions}, {total / 60:.0f} min, " \
          f"{generator} generator) to {out}"
    if generator != "legacy" and total:
        msg += f"; focused {focused / total:.1%} of the time, label noise {noise / total:.1%} of frames"
    print(msg)
    return paths


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--subjects", type=int, default=24)
    ap.add_argument("--sessions", type=int, default=2)
    ap.add_argument("--seconds", type=int, default=None,
                    help="fixed session length (default: live 600-1800 s random, legacy 600 s)")
    ap.add_argument("--min-seconds", type=int, default=600)
    ap.add_argument("--max-seconds", type=int, default=1800)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--out")
    ap.add_argument("--generator", choices=["live", "legacy"], default="live")
    ap.add_argument("--label-noise", type=float, default=0.05)
    a = ap.parse_args()
    main(a.subjects, a.sessions, a.seconds, a.seed, a.out, a.generator, a.min_seconds, a.max_seconds, a.label_noise)
