#!/usr/bin/env python3
"""Brain-content ablation: LapseForecaster WITH vs WITHOUT content features (+ the heuristic fallback
for reference), on the held-out test subjects. Writes a Markdown table, JSON and PNG to ml/reports/.

    ml/.venv/bin/python ml/forecast/ablation.py            # uses checkpoints from train.py
    ml/.venv/bin/python ml/forecast/ablation.py --seeds 0 1 2   # retrain per seed, report mean +- sd

Outputs on the SYNTHETIC corpus are named forecast_ablation_SYNTHETIC.* and titled SYNTHETIC; they
show the pipeline works and that content CAN help when lapses couple to content, nothing more.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import eval as E  # noqa: E402
import train as T  # noqa: E402

REPORTS = HERE.parent / "reports"
ROWS = ["with content", "without content", "previous model with content", "previous model without content",
        "heuristic with content", "heuristic without content"]
COLORS = {"with content": "#2a78d6", "without content": "#eb6834",
          "previous model with content": "#9cc0ea", "previous model without content": "#f3b79d",
          "heuristic with content": "#1baf7a", "heuristic without content": "#eda100"}
METRICS = [("auroc", "AUROC", "{:.3f}"), ("precision_at_alert_rate", "Precision @ 10% alert rate", "{:.3f}"),
           ("median_lead_s", "Median lead time (s)", "{:.1f}"), ("detection_rate", "Onsets warned (≤15 s)", "{:.2f}")]


def run(models, manifest, seeds, extra_manifest=None, previous_dir=None):
    if not seeds:
        res, _, meta = E.evaluate(models, manifest, previous_dir=previous_dir)
        return {k: {m: [v[m]] for m, *_ in METRICS + [("positive_rate", "", "")]} for k, v in E.strip(res).items()}, meta
    agg, meta = {}, None
    for s in seeds:
        out = pathlib.Path(models) / f"seed{s}"
        T.main(["--manifest", str(manifest), "--out", str(out), "--seed", str(s)]
               + (["--extra-manifest", str(extra_manifest)] if extra_manifest else []))
        # the previous (fixed) model is scored once; its numbers do not depend on the seed
        res, _, meta = E.evaluate(out, manifest, previous_dir=previous_dir if s == seeds[0] else None)
        for k, v in E.strip(res).items():
            for m, *_ in METRICS + [("positive_rate", "", "")]:
                agg.setdefault(k, {}).setdefault(m, []).append(v[m])
    meta["seeds"] = seeds
    return agg, meta


def fmt(vals, f):
    v = np.array(vals, float)
    return f.format(v.mean()) + (f" ± {f.format(v.std())}" if len(v) > 1 else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--models", default=str(T.DEFAULT_OUT))
    ap.add_argument("--manifest", default=str(T.DEFAULT_MANIFEST))
    ap.add_argument("--seeds", type=int, nargs="*", default=[])
    ap.add_argument("--extra-manifest", help="train-only sessions passed to train.py")
    ap.add_argument("--previous-dir", help="dir with the previously shipped LapseForecaster*.mlpackage to score too")
    a = ap.parse_args()
    agg, meta = run(a.models, a.manifest, a.seeds, a.extra_manifest, a.previous_dir)
    if a.extra_manifest:
        meta["extra_train_manifest"] = E._repo_rel(a.extra_manifest)
    syn = meta["synthetic"]
    tag, TAG = ("_SYNTHETIC", "SYNTHETIC ") if syn else ("", "")
    REPORTS.mkdir(parents=True, exist_ok=True)
    rows = [r for r in ROWS if r in agg]
    chance = np.mean(agg[rows[0]]["positive_rate"])
    lines = [f"# {TAG}LapseForecaster brain-content ablation", ""]
    if syn:
        lines += ["**SYNTHETIC DATA. Not a result.** Sensor streams, SART trials and experience-sampling answers are",
                  "generated by `ml/forecast/synth_forecast.py`; content timelines are MOCK. Lapse onsets were *made*",
                  "to depend on MOCK drift risk / valley proximity, so this only shows the pipeline works and that",
                  "content features can be used when such a coupling exists. Report real-data numbers only.", ""]
    lines += [f"Test set: {meta['test_subjects']} held-out subjects (subject-wise split), {meta['test_onsets']} lapse onsets. "
              f"Alert rate fixed at {int(meta['alert_rate'] * 100)}% of scored seconds. Chance precision = positive rate "
              f"= {chance:.3f}." + (f" Seeds: {meta['seeds']} (mean ± sd)." if meta.get("seeds") else " Single training seed."), "",
              "| Variant | " + " | ".join(t for _, t, _ in METRICS) + " |", "|---|" + "---|" * len(METRICS)]
    for r in rows:
        lines.append(f"| {TAG}{r} | " + " | ".join(fmt(agg[r][m], f) for m, _, f in METRICS) + " |")
    lines += ["", "Lead time = median seconds between the first alert in the 15 s before an onset and the onset "
              "(detected onsets only). Heuristic rows score `HeuristicLapseForecaster` default weights (Python mirror)."]
    if any(r.startswith("previous") for r in rows):
        lines += ["", "\"previous model\" rows score the Core ML models shipped before Phase 4 (trained on the older, "
                  "simpler SYNTHETIC generator) on the same held-out test subjects; they are not retrained per seed."]
    if meta.get("extra_train_manifest"):
        lines += ["", f"Training also used train-only sessions from the legacy SYNTHETIC generator "
                  f"(`{meta['extra_train_manifest']}`); validation and test subjects come only from the realistic "
                  "generator."]
    (REPORTS / f"forecast_ablation{tag}.md").write_text("\n".join(lines) + "\n")
    (REPORTS / f"forecast_ablation{tag}.json").write_text(json.dumps(
        {"synthetic": syn, "meta": meta, "results": {r: {m: agg[r][m] for m in agg[r]} for r in rows}}, indent=1, default=float))
    plot(agg, rows, meta, chance, TAG, REPORTS / f"forecast_ablation{tag}.png")
    print("\n".join(lines))


def plot(agg, rows, meta, chance, TAG, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    ink, muted, grid = "#0b0b0b", "#52514e", "#e4e3df"
    fig, axes = plt.subplots(1, 3, figsize=(13, 3.6), facecolor="#fcfcfb")
    y = np.arange(len(rows))[::-1]
    for ax, (m, title, f) in zip(axes, METRICS[:3]):
        ax.set_facecolor("#fcfcfb")
        vals = [np.mean(agg[r][m]) for r in rows]
        errs = [np.std(agg[r][m]) if len(agg[r][m]) > 1 else 0 for r in rows]
        ax.barh(y, vals, height=0.6, color=[COLORS[r] for r in rows], xerr=errs if any(errs) else None, ecolor=muted, capsize=3)
        for yi, v in zip(y, vals):
            ax.text(v, yi, "  " + f.format(v), va="center", ha="left", color=ink, fontsize=9)
        if m == "auroc":
            ax.axvline(0.5, color=muted, lw=1, ls="--"); ax.text(0.5, y[-1] - 0.6, " chance", color=muted, fontsize=8)
            ax.set_xlim(0.4, 1.0)
        elif m == "precision_at_alert_rate":
            ax.axvline(chance, color=muted, lw=1, ls="--"); ax.text(chance, y[-1] - 0.6, " chance", color=muted, fontsize=8)
            ax.set_xlim(0, 1.0)
        else:
            ax.set_xlim(0, 15)
        ax.set_title(title, color=ink, fontsize=10, loc="left")
        ax.set_yticks(y); ax.set_yticklabels(rows if ax is axes[0] else [""] * len(rows), color=muted, fontsize=9)
        ax.tick_params(colors=muted, labelsize=8)
        ax.grid(axis="x", color=grid, lw=0.8); ax.set_axisbelow(True)
        for s in ax.spines.values():
            s.set_visible(False)
    fig.suptitle(f"{TAG}LapseForecaster: with vs without brain-content features "
                 f"({meta['test_subjects']} held-out {TAG.lower().strip() + ' ' if TAG else ''}subjects, "
                 f"{meta['test_onsets']} onsets)" + ("  |  SYNTHETIC DATA, NOT A RESULT" if TAG else ""),
                 color=ink, fontsize=11, x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.92))
    fig.savefig(path, dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    main()
